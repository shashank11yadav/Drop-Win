// Generates src/tables.generated.ts from the closed-form design in
// src/table-design.ts and checks every table against the RTP target.
//
//   node scripts/tables.ts --write   regenerate the file
//   node scripts/tables.ts --check   fail if the file is stale or a table is off target

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { RISKS, ROW_COUNTS, RTP_TOLERANCE, TARGET_RTP } from '../src/game.ts';
import { formatMultiplier, rtp } from '../src/multipliers.ts';
import { designTable } from '../src/table-design.ts';

const target = fileURLToPath(new URL('../src/tables.generated.ts', import.meta.url));
const mode = process.argv[2];
if (mode !== '--write' && mode !== '--check') {
  console.error('usage: node scripts/tables.ts --write | --check');
  process.exit(2);
}

const lines: string[] = [];
const problems: string[] = [];
const summary: string[] = [];

for (const risk of RISKS) {
  lines.push(`  ${risk}: {`);
  for (const rows of ROW_COUNTS) {
    const table = designTable(rows, risk, TARGET_RTP);
    const value = rtp(table);
    if (Math.abs(value - TARGET_RTP) > RTP_TOLERANCE) {
      problems.push(`${risk}/${String(rows)}: RTP ${value.toFixed(6)} outside tolerance`);
    }
    summary.push(
      `${risk.padEnd(6)} ${String(rows).padStart(2)} rows  RTP ${(value * 100).toFixed(4)}%  edge ${formatMultiplier(table[0] ?? 0)}`,
    );
    lines.push(`    ${String(rows)}: [${table.join(', ')}],`);
  }
  lines.push('  },');
}

const source = `// Generated by packages/fairness/scripts/tables.ts. Do not edit by hand.
// Multipliers are in hundredths: 150 means 1.5x. Index = bucket = number of right bounces.
import type { Risk, RowCount } from './game.ts';

export const MULTIPLIER_TABLES: Record<Risk, Record<RowCount, readonly number[]>> = {
${lines.join('\n')}
};
`;

console.log(summary.join('\n'));

if (problems.length > 0) {
  console.error(problems.join('\n'));
  process.exit(1);
}

if (mode === '--write') {
  writeFileSync(target, source);
  console.log(`wrote ${target}`);
} else if (readFileSync(target, 'utf8') !== source) {
  console.error('tables.generated.ts is stale; run npm run tables -w @drop-win/fairness');
  process.exit(1);
} else {
  console.log('tables.generated.ts is up to date');
}
